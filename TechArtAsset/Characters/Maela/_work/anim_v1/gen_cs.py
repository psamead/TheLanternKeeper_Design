from poses import CLIPS, LIGHT_PATH
L=[]
for name,c in CLIPS.items():
  keys=c['keys']; n=len(next(iter(keys.values())))
  times=c.get('times',[round(c['length']*i/(n-1),4) for i in range(n)])
  L.append(f'        clips["{name}"] = Make("{name}", {str(c["loop"]).lower()}, new float[]{{{",".join(f"{t}f" for t in times)}}}, new (string,string,float[])[]{{')
  for k,v in keys.items():
    vs=",".join(f"{x}f" for x in v)
    if k=='LIGHT': L.append(f'            ("{LIGHT_PATH}","LIGHT",new float[]{{{vs}}}),')
    elif k.endswith(':y'): L.append(f'            ("{k[:-2]}","m_LocalPosition.y",new float[]{{{vs}}}),')
    else: L.append(f'            ("{k}","localEulerAnglesRaw.z",new float[]{{{vs}}}),')
  L.append('        });')
body="\n".join(L)
cs=f'''// Generated by SharedWorkFolder/TechArtAsset/Characters/Maela/_work/anim_v1/gen_cs.py — edit poses.py, not this file.
// Menu: Tools > Lantern Keeper > Build Maela Animations. Touches only .anim files and Maela.controller; never the .psb.
using System.Collections.Generic;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using UnityEngine.Rendering.Universal;

public static class MaelaAnimBuilder
{{
    const string Dir = "Assets/_Project/Art/Characters/Maela/";

    [MenuItem("Tools/Lantern Keeper/Build Maela Animations")]
    public static void Build()
    {{
        var clips = new Dictionary<string, AnimationClip>();
{body}
        var ctrl = AssetDatabase.LoadAssetAtPath<AnimatorController>(Dir + "Maela.controller");
        AddParam(ctrl, "Speed", AnimatorControllerParameterType.Float);
        AddParam(ctrl, "Grounded", AnimatorControllerParameterType.Bool);
        AddParam(ctrl, "VelY", AnimatorControllerParameterType.Float);
        AddParam(ctrl, "RaiseLantern", AnimatorControllerParameterType.Trigger);
        var sm = ctrl.layers[0].stateMachine;
        var idle = Find(sm, "Idle");
        var run = State(sm, "Run", clips["Maela_Run"], new Vector3(450, 0));
        var up = State(sm, "JumpUp", clips["Maela_JumpUp"], new Vector3(450, 150));
        var fall = State(sm, "Fall", clips["Maela_Fall"], new Vector3(450, 300));
        var lan = State(sm, "Lantern", clips["Maela_Lantern"], new Vector3(200, 300));
        foreach (var s in new[] {{ idle, run, up, fall, lan }})
            foreach (var t in s.transitions) s.RemoveTransition(t);
        foreach (var t in sm.anyStateTransitions) sm.RemoveAnyStateTransition(t);

        T(idle, run, 0.08f).AddCondition(AnimatorConditionMode.Greater, 0.1f, "Speed");
        T(run, idle, 0.1f).AddCondition(AnimatorConditionMode.Less, 0.1f, "Speed");
        foreach (var g in new[] {{ idle, run }})
        {{
            var j = T(g, up, 0.05f); j.AddCondition(AnimatorConditionMode.IfNot, 0, "Grounded"); j.AddCondition(AnimatorConditionMode.Greater, 0.01f, "VelY");
            var f = T(g, fall, 0.1f); f.AddCondition(AnimatorConditionMode.IfNot, 0, "Grounded"); f.AddCondition(AnimatorConditionMode.Less, -0.01f, "VelY");
            T(g, lan, 0.08f).AddCondition(AnimatorConditionMode.If, 0, "RaiseLantern");
        }}
        T(up, fall, 0.12f).AddCondition(AnimatorConditionMode.Less, 0f, "VelY");
        var l1 = T(fall, idle, 0.06f); l1.AddCondition(AnimatorConditionMode.If, 0, "Grounded"); l1.AddCondition(AnimatorConditionMode.Less, 0.1f, "Speed");
        var l2 = T(fall, run, 0.06f); l2.AddCondition(AnimatorConditionMode.If, 0, "Grounded"); l2.AddCondition(AnimatorConditionMode.Greater, 0.1f, "Speed");
        var l3 = T(up, idle, 0.06f); l3.AddCondition(AnimatorConditionMode.If, 0, "Grounded");
        var back = T(lan, idle, 0.1f); back.hasExitTime = true; back.exitTime = 0.95f;
        EditorUtility.SetDirty(ctrl);
        AssetDatabase.SaveAssets();
        Debug.Log("Maela animations built: Run / JumpUp / Fall / Lantern");
    }}

    static AnimationClip Make(string name, bool loop, float[] times, (string path, string prop, float[] v)[] curves)
    {{
        string p = Dir + name + ".anim";
        var clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(p);
        if (clip == null) {{ clip = new AnimationClip {{ frameRate = 60 }}; AssetDatabase.CreateAsset(clip, p); }}
        clip.ClearCurves();
        foreach (var c in curves)
        {{
            var ac = new AnimationCurve();
            for (int i = 0; i < times.Length; i++) ac.AddKey(new Keyframe(times[i], c.v[i]));
            for (int i = 0; i < ac.length; i++) AnimationUtility.SetKeyLeftTangentMode(ac, i, AnimationUtility.TangentMode.ClampedAuto);
            for (int i = 0; i < ac.length; i++) AnimationUtility.SetKeyRightTangentMode(ac, i, AnimationUtility.TangentMode.ClampedAuto);
            if (c.prop == "LIGHT")
                AnimationUtility.SetEditorCurve(clip, EditorCurveBinding.FloatCurve(c.path, typeof(Light2D), "m_Intensity"), ac);
            else
                AnimationUtility.SetEditorCurve(clip, EditorCurveBinding.FloatCurve(c.path, typeof(Transform), c.prop), ac);
        }}
        var s = AnimationUtility.GetAnimationClipSettings(clip);
        s.loopTime = loop;
        AnimationUtility.SetAnimationClipSettings(clip, s);
        EditorUtility.SetDirty(clip);
        return clip;
    }}
    static void AddParam(AnimatorController c, string n, AnimatorControllerParameterType t)
    {{ foreach (var p in c.parameters) if (p.name == n) return; c.AddParameter(n, t); }}
    static AnimatorState Find(AnimatorStateMachine sm, string n)
    {{ foreach (var s in sm.states) if (s.state.name == n) return s.state; return null; }}
    static AnimatorState State(AnimatorStateMachine sm, string n, Motion m, Vector3 pos)
    {{ var s = Find(sm, n) ?? sm.AddState(n, pos); s.motion = m; s.writeDefaultValues = true; return s; }}
    static AnimatorStateTransition T(AnimatorState a, AnimatorState b, float dur)
    {{ var t = a.AddTransition(b); t.hasExitTime = false; t.duration = dur; t.hasFixedDuration = true; return t; }}
}}
'''
open('MaelaAnimBuilder.cs','w').write(cs)
